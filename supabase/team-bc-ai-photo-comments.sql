-- Team BC: shared, team-isolated comments for BC AI uploaded photos
create table if not exists public.team_bc_ai_photo_comments (
  id bigint generated by default as identity primary key,
  team_key text not null references public.teams(team_key) on delete cascade,
  photo_path text not null,
  user_id uuid not null references auth.users(id) on delete cascade,
  comment_text text not null check (char_length(trim(comment_text)) between 1 and 1000),
  created_at timestamptz not null default now()
);

create index if not exists team_bc_ai_photo_comments_photo_idx
  on public.team_bc_ai_photo_comments (team_key, photo_path, created_at);

alter table public.team_bc_ai_photo_comments enable row level security;

drop policy if exists "Team members can read BC AI photo comments" on public.team_bc_ai_photo_comments;
create policy "Team members can read BC AI photo comments"
on public.team_bc_ai_photo_comments for select to authenticated
using (
  exists (
    select 1 from public.team_memberships tm
    where tm.user_id = auth.uid() and tm.team_key = team_bc_ai_photo_comments.team_key
  )
);

drop policy if exists "Team members can add BC AI photo comments" on public.team_bc_ai_photo_comments;
create policy "Team members can add BC AI photo comments"
on public.team_bc_ai_photo_comments for insert to authenticated
with check (
  user_id = auth.uid()
  and exists (
    select 1 from public.team_memberships tm
    where tm.user_id = auth.uid() and tm.team_key = team_bc_ai_photo_comments.team_key
  )
);

drop policy if exists "Authors or team admins can delete BC AI photo comments" on public.team_bc_ai_photo_comments;
create policy "Authors or team admins can delete BC AI photo comments"
on public.team_bc_ai_photo_comments for delete to authenticated
using (
  user_id = auth.uid()
  or exists (
    select 1 from public.team_memberships tm
    where tm.user_id = auth.uid()
      and tm.team_key = team_bc_ai_photo_comments.team_key
      and tm.role in ('owner','admin')
  )
);

grant select, insert, delete on public.team_bc_ai_photo_comments to authenticated;
grant usage, select on sequence public.team_bc_ai_photo_comments_id_seq to authenticated;
